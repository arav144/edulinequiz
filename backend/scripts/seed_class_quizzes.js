async function seed() {
  try {
    console.log('Connecting to MongoDB Atlas...');
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected.');

    // 1. Ensure Subject exists (Hindi)
    let subject = await Subject.findOne({ name: { $regex: /^hindi$/i } });
    if (!subject) {
      subject = await Subject.create({ name: 'Hindi' });
      console.log('Created Subject:', subject.name);
    } else {
      console.log('Using Subject:', subject.name);
    }

    let totalQuizzes = 0;
    let totalQuestions = 0;

    for (const item of classQuizData) {
      // Find or create quiz for this target class
      let quiz = await Quiz.findOne({
        subjectId: subject._id,
        targetClass: item.targetClass,
      });

      if (!quiz) {
        quiz = await Quiz.create({
          name: item.quizName,
          subjectId: subject._id,
          targetClass: item.targetClass,
          numberOfQuestions: item.questions.length,
          timePerQuestion: 30,
          description: item.description,
          instructions:
            'प्रत्येक प्रश्न को ध्यानपूर्वक पढ़ें और दिए गए विकल्पों में से सही उत्तर चुनें।\nसभी प्रश्नों के उत्तर देना अनिवार्य है।\nउत्तर चुनने के बाद ‘आगे बढ़ें’ बटन दबाकर आगे बढ़ें।\nसभी प्रश्न पूरे करने के बाद ‘जमा करें’ बटन पर क्लिक करें।\nप्रतियोगिता पूरी होने के बाद अपना स्कोर/परिणाम देखें।',
          contactInfo: '+91 92174 78822',
          language: 'hi',
          status: 'Published',
          passingPercentage: 50,
        });
        console.log(`Created Quiz for ${item.targetClass}:`, quiz.name, quiz._id);
      } else {
        quiz.name = item.quizName;
        quiz.description = item.description;
        quiz.status = 'Published';
        quiz.numberOfQuestions = item.questions.length;
        await quiz.save();
        console.log(`Updated Quiz for ${item.targetClass}:`, quiz.name);
      }

      totalQuizzes++;

      // Clean old questions for this specific quiz
      await Question.deleteMany({ quizId: quiz._id });

      // Insert 10 questions for this class
      const docs = item.questions.map((q) => ({
        quizId: quiz._id,
        subjectId: subject._id,
        question: q.question,
        options: q.options,
        correctAnswer: q.correctAnswer,
        explanation: q.explanation,
      }));

      const inserted = await Question.insertMany(docs);
      console.log(`  Inserted ${inserted.length} questions for ${item.targetClass}.`);
      totalQuestions += inserted.length;
    }

    // Also update any old quiz without targetClass to have targetClass: 'Class 8' or 'All'
    await Quiz.updateMany(
      { targetClass: { $exists: false } },
      { $set: { targetClass: 'All' } }
    );

    console.log(`\n🎉 SEED COMPLETED SUCCESSFULLY!`);
    console.log(`Total Quizzes configured: ${totalQuizzes}`);
    console.log(`Total Questions inserted: ${totalQuestions}`);

    process.exit(0);
  } catch (err) {
    console.error('Seeding error:', err);
    process.exit(1);
  }
}

seed();
